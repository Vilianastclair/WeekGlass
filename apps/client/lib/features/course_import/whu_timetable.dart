String whuHash(String value) => sha256.convert(utf8.encode(value)).toString();
// Some teaching-office fields contain presentation markup or HTML spaces.
String schoolText(Object? value) => (value?.toString() ?? '')
    .replaceAll(RegExp(r'&(?:nbsp|#0*160|#x0*a0);', caseSensitive: false), ' ')
    .replaceAll('&amp;', '&')
    .replaceAll('&quot;', '"')
    .replaceAll('&#39;', "'")
    .replaceAll('&lt;', '<')
    .replaceAll('&gt;', '>')
    .replaceAll(RegExp(r'<br\s*/?>', caseSensitive: false), ',')
    .replaceAll(RegExp(r'<[^>]*>'), '')
    .replaceAll(RegExp('[\u200b\ufeff]'), '')
    .trim();
String eventImportFingerprint(CalendarEvent e) => whuHash(
  jsonEncode([
    e.title,
    e.notes,
    e.startUtc?.toIso8601String(),
    e.endUtc?.toIso8601String(),
  ]),
);

/// Remove only the exact footer generated by releases before 0.12.
/// User text before or after it, and existing manual-edit protection, survive.
CalendarEvent compactLegacyWhuNotes(CalendarEvent event) {
  if (event.isAllDay ||
      !(event.importSource?.startsWith('whu:') ?? false) ||
      event.notes == null) {
    return event;
  }
  final pattern = RegExp(
    r'(?:^|\n)\d{4}[–-]\d{4} (?:秋季|春季|夏季)学期 · 第 \d+ 周 · 第 [\d、]+ 节\r?\n来源：武汉大学教务系统(?=\r?\n|$)',
  );
  if (!pattern.hasMatch(event.notes!)) return event;
  final cleaned = event.notes!.replaceFirst(pattern, '').trim();
  if (cleaned == event.notes) return event;
  final wasUnmodified =
      event.importFingerprint == eventImportFingerprint(event);
  final updated = event.withDetails(
    title: event.title,
    color: event.color,
    notes: cleaned.isEmpty ? null : cleaned,
  );
  return copyImported(
    updated,
    fingerprint: wasUnmodified
        ? eventImportFingerprint(updated)
        : event.importFingerprint,
  );
}

class WhuTerm {
  const WhuTerm(this.year, this.semester);
  final int year;
  final int semester;
  String get key => '$year-$semester';
  int? get calendarWeeks => year != 2026
      ? null
      : switch (semester) {
          3 => 19,
          12 => 18,
          16 => 4,
          _ => null,
        };
  // 2026–2027 calendar supplied by the user; later years need confirmation.
  DateTime? get calendarFirstMonday => year != 2026
      ? null
      : switch (semester) {
          3 => DateTime(2026, 9, 7),
          12 => DateTime(2027, 2, 22),
          _ => null,
        };
  String get label =>
      '$year–${year + 1} ${switch (semester) {
        3 => '秋季',
        12 => '春季',
        _ => '夏季',
      }}学期';
}

class ClassPeriod {
  const ClassPeriod(this.start, this.end);
  final int start;
  final int end;
  String get label => '${clock(start)} – ${clock(end)}';
  static String clock(int minute) =>
      '${(minute ~/ 60).toString().padLeft(2, '0')}:${(minute % 60).toString().padLeft(2, '0')}';

  static List<ClassPeriod> parseClock(String text) {
    final lines = text
        .split('\n')
        .map((line) => line.trim())
        .where((line) => line.isNotEmpty)
        .toList();
    if (lines.isEmpty || lines.length > 24) {
      throw const FormatException('请填写 1–24 个节次的开始和结束时刻。');
    }
    final result = <ClassPeriod>[];
    for (var index = 0; index < lines.length; index++) {
      final match = RegExp(
        r'^(?:第\s*)?(\d{1,2})(?:\s*节)?\s*[:：、.\s]\s*(\d{1,2})[:：](\d{2})\s*[-—–－~～至]\s*(\d{1,2})[:：](\d{2})$',
      ).firstMatch(lines[index]);
      if (match == null || int.parse(match[1]!) != index + 1) {
        throw FormatException(
          '第 ${index + 1} 行节次时间格式应为“${index + 1} 08:00-08:45”，并从第 1 节连续排列。',
        );
      }
      final sh = int.parse(match[2]!),
          sm = int.parse(match[3]!),
          eh = int.parse(match[4]!),
          em = int.parse(match[5]!);
      final start = sh * 60 + sm, end = eh * 60 + em;
      if (sh > 23 ||
          eh > 23 ||
          sm > 59 ||
          em > 59 ||
          end <= start ||
          (result.isNotEmpty && start < result.last.end)) {
        throw FormatException('第 ${index + 1} 节时间无效或与上一节重叠。');
      }
      result.add(ClassPeriod(start, end));
    }
    return result;
  }

  // Wuhan University 2026–2027 calendar. Still editable for special arrangements.
  static const standard = [
    ClassPeriod(480, 525),
    ClassPeriod(530, 575),
    ClassPeriod(590, 635),
    ClassPeriod(640, 685),
    ClassPeriod(690, 735),
    ClassPeriod(845, 890),
    ClassPeriod(895, 940),
    ClassPeriod(945, 990),
    ClassPeriod(1000, 1045),
    ClassPeriod(1050, 1095),
    ClassPeriod(1110, 1155),
    ClassPeriod(1160, 1205),
    ClassPeriod(1210, 1255),
  ];
}

class WhuCourseMeeting {
  const WhuCourseMeeting({
    required this.courseKey,
    required this.title,
    required this.weekday,
    required this.periods,
    required this.weeks,
    required this.weekText,
    required this.room,
    required this.teacher,
    this.note = '',
    this.fixedTime,
  });
  final String courseKey, title, weekText, room, teacher, note;
  final int weekday;
  final List<int> periods, weeks;

  /// The source can specify actual clock times instead of (or in addition to) nodes.
  final ClassPeriod? fixedTime;
  String get scheduleLabel => [
    '周${'一二三四五六日'[weekday - 1]}',
    if (periods.isNotEmpty) '第 ${periods.join('、')} 节',
    if (fixedTime != null) fixedTime!.label,
    weekText,
  ].join(' · ');
}

class WhuTimetable {
  const WhuTimetable({
    required this.meetings,
    required this.warnings,
    required this.account,
    this.suggestedClock,
    this.suggestedFirstMonday,
  });
  final List<WhuCourseMeeting> meetings;
  final List<String> warnings;
  final String account;
  final List<ClassPeriod>? suggestedClock;
  final DateTime? suggestedFirstMonday;
  Set<String> get courseKeys => meetings.map((e) => e.courseKey).toSet();

  factory WhuTimetable.parse(Object? response) {
    if (response is String) response = jsonDecode(response);
    if (response is! Map || response['kbList'] is! List) {
      throw const FormatException('没有读到课表。请确认已登录教务系统，再重新读取。');
    }
    final rows = response['kbList'] as List;
    if (rows.length > 1000) throw const FormatException('课表条目过多，请核对学期。');
    String field(Map row, List<String> keys) {
      for (final k in keys) {
        final value = row[k];
        if (value != null && value.toString().trim().isNotEmpty) {
          return schoolText(value);
        }
      }
      return '';
    }

    final xsxx = response['xsxx'];
    final account = xsxx is Map
        ? field(xsxx, ['XH', 'xh'])
        : field(response, ['xh', 'XH']);
    final meetings = <WhuCourseMeeting>[];
    final warnings = <String>[];
    final seen = <String>{};
    for (final row in rows) {
      if (row is! Map) {
        warnings.add('有一条课程格式无法识别。');
        continue;
      }
      final title = field(row, ['kcmc', 'KCMC']);
      try {
        if (title.isEmpty) throw const FormatException('课程名称缺失');
        final dayValue = field(row, ['xqj', 'XQJ']);
        final weekday = int.tryParse(dayValue) ?? 0;
        if (weekday < 1 || weekday > 7) throw const FormatException('星期无法识别');
        final periods = parsePeriods(field(row, ['jcs', 'jcd', 'JCS']));
        final weekText = field(row, ['zcd', 'ZCD']);
        final weeks = parseTeachingWeeks(weekText);
        final room = field(row, ['cdmc', 'CDMC']);
        final teacher = field(row, ['xm', 'XM', 'jsmc']);
        final courseId = field(row, [
          'jxb_id',
          'JXB_ID',
          'kch_id',
          'KCH_ID',
          'kch',
        ]);
        final key = whuHash(courseId.isEmpty ? '$title|$teacher' : courseId)
            .substring(0, 24);
        final signature = jsonEncode([
          key,
          weekday,
          periods,
          weeks,
          room,
          teacher,
        ]);
        if (!seen.add(signature)) continue;
        meetings.add(
          WhuCourseMeeting(
            courseKey: key,
            title: title,
            weekday: weekday,
            periods: periods,
            weeks: weeks,
            weekText: weekText,
            room: room,
            teacher: teacher,
          ),
        );
      } on FormatException catch (e) {
        warnings.add('${title.isEmpty ? '未命名课程' : title}：${e.message}');
      }
    }
    final practice = response['sjkList'];
    if (practice is List) {
      for (final row in practice) {
        final title = row is Map ? field(row, ['kcmc', 'KCMC']) : '';
        warnings.add('${title.isEmpty ? '实践教学' : title}：教务未提供可安排的星期与节次，未放入周历。');
      }
    }
    return WhuTimetable(
      meetings: meetings,
      warnings: warnings,
      account: account,
    );
  }

  List<CalendarEvent> expand({
    required WhuTerm term,
    required String accountKey,
    required DateTime firstMonday,
    required List<ClassPeriod> clock,
    Set<String>? selectedCourses,
    String schoolId = 'whu',
  }) {
    if (accountKey.trim().isEmpty) throw ArgumentError('请填写学号，用于区分不同账号的课表。');
    if (firstMonday.weekday != DateTime.monday) {
      throw ArgumentError('第一教学周须选择周一。');
    }
    final chosen = meetings.where(
      (m) => selectedCourses == null || selectedCourses.contains(m.courseKey),
    );
    if (clock.length > 24 ||
        (clock.isEmpty &&
            (chosen.isEmpty || chosen.any((m) => m.fixedTime == null)))) {
      throw ArgumentError('请核对节次时间。');
    }
    for (var i = 0; i < clock.length; i++) {
      final p = clock[i];
      if (p.start < 0 ||
          p.end > 1440 ||
          p.end <= p.start ||
          (i > 0 && p.start < clock[i - 1].end)) {
        throw ArgumentError('节次时间须按顺序排列，且结束晚于开始。');
      }
    }
    final prefix = scopeFor(term, accountKey, schoolId: schoolId);
    final output = <CalendarEvent>[];
    // Stable ordering keeps a meeting's identity across room/time changes.
    final ordered = [...meetings]
      ..sort((a, b) {
        final key = a.courseKey.compareTo(b.courseKey);
        if (key != 0) return key;
        final day = a.weekday.compareTo(b.weekday);
        if (day != 0) return day;
        return (a.periods.firstOrNull ?? 25).compareTo(
          b.periods.firstOrNull ?? 25,
        );
      });
    final ordinals = <String, int>{};
    for (final m in ordered) {
      final dayKey = '${m.courseKey}:${m.weekday}';
      final ordinal = ordinals.update(dayKey, (n) => n + 1, ifAbsent: () => 0);
      if (selectedCourses != null && !selectedCourses.contains(m.courseKey)) {
        continue;
      }
      if (m.fixedTime == null && m.periods.last > clock.length) {
        throw ArgumentError('“${m.title}”需要第 ${m.periods.last} 节的时间。');
      }
      // Split non-contiguous periods instead of inventing teaching through a gap.
      final times = <ClassPeriod>[];
      if (m.fixedTime case final fixed?) {
        times.add(fixed);
      } else {
        final runs = <List<int>>[];
        for (final p in m.periods) {
          if (runs.isEmpty || p != runs.last.last + 1) {
            runs.add([p]);
          } else {
            runs.last.add(p);
          }
        }
        for (final run in runs) {
          times.add(
            ClassPeriod(clock[run.first - 1].start, clock[run.last - 1].end),
          );
        }
      }
      for (final week in m.weeks) {
        final date = DateTime(
          firstMonday.year,
          firstMonday.month,
          firstMonday.day + (week - 1) * 7 + m.weekday - 1,
        );
        for (var part = 0; part < times.length; part++) {
          final start = times[part].start;
          final end = times[part].end;
          final source =
              '$prefix${m.courseKey}:${m.weekday}:$ordinal:$week:$part';
          final notes = [
            if (m.room.isNotEmpty) '地点：${m.room}',
            if (m.teacher.isNotEmpty) '教师：${m.teacher}',
            if (m.note.isNotEmpty) m.note,
          ].join('\n');
          final event = CalendarEvent.timed(
            id: '$schoolId-${whuHash(source)}',
            title: m.title,
            notes: notes,
            color:
                EventColor.values[int.parse(
                      m.courseKey.substring(0, 4),
                      radix: 16,
                    ) %
                    EventColor.values.length],
            startLocal: DateTime(date.year, date.month, date.day, 0, start),
            endLocal: DateTime(date.year, date.month, date.day, 0, end),
            timeZoneId: 'Asia/Shanghai',
            seriesId: '$prefix${m.courseKey}',
            recurrenceRule: 'FREQ=WEEKLY',
            importSource: source,
          );
          output.add(
            copyImported(event, fingerprint: eventImportFingerprint(event)),
          );
        }
      }
    }
    if (output.length > 5000) throw ArgumentError('单次最多导入 5000 节课程，请核对教学周。');
    return output;
  }

  static String scopeFor(
    WhuTerm term,
    String accountKey, {
    String schoolId = 'whu',
  }) {
    if (!RegExp(r'^[a-z][a-z0-9_]{0,31}$').hasMatch(schoolId)) {
      throw ArgumentError('学校标识无效。');
    }
    return '$schoolId:${whuHash(accountKey.trim()).substring(0, 24)}:${term.key}:';
  }
}

List<int> parseTeachingWeeks(String value) {
  var text = schoolText(value)
      .replaceAll(RegExp(r'\s'), '')
      .replaceAll('第', '')
      .replaceAll('（', '(')
      .replaceAll('）', ')')
      .replaceAll('，', ',')
      .replaceAll('、', ',')
      .replaceAll('；', ',')
      .replaceAll(';', ',')
      .replaceAll('－', '-')
      .replaceAll('—', '-')
      .replaceAll('～', '-')
      .replaceAll('至', '-')
      .replaceAll('(周)', '周');
  final out = <int>{};
  for (final part in text.split(',')) {
    if (part.isEmpty && text.endsWith(',')) continue;
    final match = RegExp(r'^(\d{1,2})(?:周?-(\d{1,2}))?周?(?:\(([单双])周?\))?周?$')
        .firstMatch(part);
    if (match == null) throw FormatException('教学周“$text”无法识别，请核对原课表');
    final first = int.parse(match[1]!);
    final last = int.parse(match[2] ?? match[1]!);
    if (first < 1 || last > 53 || last < first) {
      throw const FormatException('教学周超出 1–53 周');
    }
    for (var n = first; n <= last; n++) {
      if (match[3] == null || (match[3] == '单' ? n.isOdd : n.isEven)) {
        out.add(n);
      }
    }
  }
  if (out.isEmpty) throw const FormatException('没有有效的教学周');
  return out.toList()..sort();
}

List<int> parsePeriods(String value) {
  var text = value
      .replaceAll(RegExp(r'[\s节第\[\]【】]'), '')
      .replaceAll('，', ',')
      .replaceAll('、', ',')
      .replaceAll('－', '-')
      .replaceAll('—', '-');
  final out = <int>{};
  for (final part in text.split(',')) {
    final m = RegExp(r'^(\d{1,2})(?:-(\d{1,2}))?$').firstMatch(part);
    if (m == null) throw const FormatException('节次无法识别');
    final first = int.parse(m[1]!);
    final last = int.parse(m[2] ?? m[1]!);
    if (first < 1 || last > 24 || first > last) {
      throw const FormatException('节次超出 1–24 节');
    }
    for (var n = first; n <= last; n++) {
      out.add(n);
    }
  }
  return out.toList()..sort();
}

CalendarEvent copyImported(
  CalendarEvent event, {
  String? fingerprint,
  CalendarEvent? previous,
}) => CalendarEvent.timed(
  id: previous?.id ?? event.id,
  title: event.title,
  notes: event.notes,
  color: previous?.color ?? event.color,
  startLocal: event.startLocal,
  endLocal: event.endLocal,
  timeZoneId: event.timeZoneId,
  seriesId: event.seriesId,
  recurrenceRule: event.recurrenceRule,
  importSource: event.importSource,
  importFingerprint: fingerprint ?? event.importFingerprint,
  createdAtUtc: previous?.createdAtUtc ?? event.createdAtUtc,
  version: previous == null ? event.version : previous.version + 1,
);

class CourseImportPlan {
  const CourseImportPlan({
    required this.changes,
    required this.added,
    required this.updated,
    required this.removed,
    required this.unchanged,
    required this.keptEdits,
    required this.keptDeleted,
    required this.duplicates,
  });
  final List<CalendarEvent> changes;
  final int added,
      updated,
      removed,
      unchanged,
      keptEdits,
      keptDeleted,
      duplicates;
  factory CourseImportPlan.compare({
    required List<CalendarEvent> incoming,
    required List<CalendarEvent> previous,
    required List<CalendarEvent> allActive,
    bool removeMissing = false,
    bool restoreDeleted = false,
    Set<String> excludedSources = const {},
    Set<String> preservedSources = const {},
  }) {
    final existing = {for (final e in previous) e.importSource: e};
    final present = incoming.map((e) => e.importSource).toSet();
    final changes = <CalendarEvent>[];
    var added = 0,
        updated = 0,
        removed = 0,
        unchanged = 0,
        keptEdits = 0,
        keptDeleted = 0,
        duplicates = 0;
    final fingerprints = {
      for (final e in allActive)
        jsonEncode([
          e.title,
          e.startUtc?.toIso8601String(),
          e.endUtc?.toIso8601String(),
        ]),
    };
    for (final fresh in incoming) {
      final old = existing[fresh.importSource];
      if (old != null) {
        if (old.deletedAtUtc != null) {
          if (restoreDeleted) {
            changes.add(copyImported(fresh, previous: old));
            added++;
          } else {
            keptDeleted++;
          }
          continue;
        }
        if (old.importFingerprint != eventImportFingerprint(old)) {
          keptEdits++;
          continue;
        }
        if (old.importFingerprint == fresh.importFingerprint) {
          unchanged++;
          continue;
        }
        changes.add(copyImported(fresh, previous: old));
        updated++;
      } else {
        final key = jsonEncode([
          fresh.title,
          fresh.startUtc?.toIso8601String(),
          fresh.endUtc?.toIso8601String(),
        ]);
        if (!fingerprints.add(key)) {
          duplicates++;
          continue;
        }
        changes.add(fresh);
        added++;
      }
    }
    if ((removeMissing && incoming.isNotEmpty) || excludedSources.isNotEmpty) {
      for (final old in previous) {
        if (old.deletedAtUtc != null ||
            present.contains(old.importSource) ||
            preservedSources.contains(old.importSource) ||
            (!excludedSources.contains(old.importSource) &&
                !(removeMissing && incoming.isNotEmpty))) {
          continue;
        }
        if (old.importFingerprint != eventImportFingerprint(old)) {
          keptEdits++;
          continue;
        }
        changes.add(old.markedDeleted(DateTime.now().toUtc()));
        removed++;
      }
    }
    return CourseImportPlan(
      changes: changes,
      added: added,
      updated: updated,
      removed: removed,
      unchanged: unchanged,
      keptEdits: keptEdits,
      keptDeleted: keptDeleted,
      duplicates: duplicates,
    );
  }
}
