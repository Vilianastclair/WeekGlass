"""Generate matched school routes, not claims of live authentication.
Offline: python build_wakeup_bindings.py --inputs <directory with timetable.json, sleepy.json, legacy.kt>
Online: downloads only the three pinned upstream sources, never school websites.
"""
import argparse
import collections
import json
import re
from urllib.parse import parse_qs, urlsplit, urlunsplit
from urllib.request import urlopen
from build_school_catalog import ROOT, UPSTREAM, CROSSCHECK, OFFICIAL, build, literal
from priority_school_ledger import ADMISSIONS, aliases, render_ledger
from wakeup_school_sources import SPECIAL, ENTRIES, EXTRA_READ, CAMPUS_DOMAINS

LEGACY = ("https://raw.githubusercontent.com/dIT8Zv/WakeupSchedule_BUPT/88d5b2ff93b946b40e8ade6851d4440188443a7f/"
          "app/src/main/java/com/suda/yzune/wakeupschedule/schedule_import/SchoolListActivity.kt")
MODERN = {
    'zhengfang_new':('zf_new','NewZFParser'), 'qiangzhi':('qz','QzParser'),
    'qiangzhi_old':('qz_old','OldQzParser'), 'urp':('urp','UrpParser'),
    'urp_new':('urp_new','NewUrpParser'),
    'kingosoft_new':('kingo_new','KingosoftZXParser'),
    'kingosoft':('kingo','KingosoftZXParser'), 'wisedu':('wisedu','JinZhiParser'),
}
HISTORIC = dict(ZF='ZhengFangParser', ZF_1='zf_1', ZF_NEW='NewZFParser',
    CF='ChengFangParser', QZ='QzParser', QZ_WITH_NODE='QzWithNodeParser',
    QZ_OLD='OldQzParser', QZ_BR='QzBrParser', QZ_CRAZY='QzCrazyParser',
    URP='UrpParser', URP_NEW='NewUrpParser', PKU='PekingParser', BNUZ='BNUZParser',
    HNIU='HNIUParser', HNUST='HNUSTParser')
HEADER = '// Generated by tooling/scripts/build_wakeup_bindings.py. Do not hand edit.\n'
DEST = ROOT/'apps/client/lib/features/course_import'

def route(url):
    try:
        u=urlsplit(url)
        return bool(u.hostname and (u.hostname.endswith('.edu.cn') or u.hostname in CAMPUS_DOMAINS)
            and u.scheme=='https' and not u.query and not u.fragment and u.username is None
            and u.password is None and (u.port is None or 0<u.port<=65535)
            and re.fullmatch(r"/[A-Za-z0-9_.*%/~-]*|",u.path) and '..' not in u.path)
    except ValueError:
        return False

def academic_entry(url):
    """Only follow declarative same-university destinations; never replay tickets.

    A historical HTTP website is opened with TLS or not opened at all. Do not
    infer an HTTPS equivalent for nonstandard HTTP ports or campus IPs.
    """
    u=urlsplit(url)
    if not u.hostname or not u.hostname.endswith('.edu.cn') or u.username or u.password:
        return None
    if u.scheme=='http' and u.port in (None,80):
        u=u._replace(scheme='https',netloc=u.hostname)
    if u.scheme!='https':return None
    domain='.'.join(u.hostname.split('.')[-3:])
    for key,vals in parse_qs(u.query).items():
        if key.lower() not in ('service','redirect_uri','refer'):continue
        for dest in vals:
            v=urlsplit(dest)
            if (route(dest) and v.hostname and
                (v.hostname==domain or v.hostname.endswith('.'+domain))):
                return dest
    # Strip auth state and query/fragment rather than distribute personal or
    # expiring URLs. For a gateway, open the portal, not its orphaned callback.
    if u.query or u.fragment:
        u=u._replace(query='',fragment='',path='/')
    clean=urlunsplit(u)
    return clean if route(clean) else None

def generate(rows,checks,legacy):
    sites=build(rows,checks)
    bindings={n:s.split() for n,s in SPECIAL.items()}
    legacy_rows=re.findall(r'^\s*add\(SchoolInfo\("[A-Z]",\s*"([^"]+)",\s*"([^"]*)",\s*TYPE_([A-Z0-9_]+)\)\)',legacy,re.M)
    refs=collections.defaultdict(set)
    for r in checks:
        try: h=urlsplit(r.get('url') or '').hostname
        except ValueError: continue
        refs[(r['name'],h)].add(r.get('type'))
    def add(n,i):
        if n=='武汉大学':return
        if i not in bindings.setdefault(n,[]):bindings[n].append(i)
    for r in rows:
        n,url,t=r['name'],r['url'],r['type']
        if n=='武汉大学':continue
        h=urlsplit(url).hostname
        corroboration=refs.get((n,h),set())
        m=MODERN.get(t)
        if m and m[0] in corroboration:
            add(n,m[1])
        elif t=='qiangzhi' and 'qz_with_node' in corroboration:
            add(n,'QzWithNodeParser')
        # The family is a routing hint. The reader must still match the actual
        # personal timetable/selection-results DOM; never infer courses from a host.
        if n in bindings and corroboration:
            entry=academic_entry(url)
            if entry:sites.setdefault(n,entry)
    for n,url,t in legacy_rows:
        if t not in HISTORIC or n=='武汉大学' or n in ('其他','其它') or '教务系统' in n:continue
        add(n,HISTORIC[t])
        if route(url):sites.setdefault(n,url)
    sites.update(ENTRIES)
    sites={n:urlunsplit(urlsplit(u)) for n,u in sites.items()}
    for n in OFFICIAL:
        if n not in bindings and n!='上海大学':add(n,'NewZFParser')
    # Explicit admissions carry both the selected portal and its intended reader.
    for name, item in ADMISSIONS.items():
        if not route(item['entry']):
            raise ValueError(f'invalid reviewed entry for {name}')
        sites[name] = item['entry']
        add(name,item['parser'])
        bindings[name].remove(item['parser'])
        bindings[name].insert(0,item['parser'])
    # Every previously bundled shortcut retains at least its declared reader.
    for n in sites:
        if n not in bindings:raise ValueError(f'missing parser for {n}')
    return sites,bindings

def emit(sites,bindings):
    def strings(arr):
        return '['+', '.join(map(literal,arr))+']'
    def dmap(name,m,value):
        return 'const '+name+' = <String, '+('String' if value is literal else 'List<String>')+'>{\n'+''.join(
            f'  {literal(k)}: {value(v)},\n' for k,v in sorted(m.items()))+'};\n'
    schools=HEADER+'// Navigation URLs are not a list of account-tested schools.\nconst schoolPortalCatalog = <({String name, String entry})>[\n'
    for name,url in sorted(sites.items()):
        schools+=f'  (name: {literal(name)}, entry: {literal(url)}),\n'
    (DEST/'school_portal_catalog.dart').write_text(schools+'];\n',encoding='utf8')
    code=HEADER+"import 'school_portal_catalog.dart';\n\n"+dmap('wakeupSchoolBindings',bindings,strings)+'\n'
    code+=dmap('prioritySchoolAliases',aliases(),strings)+'\n'
    code+=dmap('wakeupReadOrigins',EXTRA_READ,strings)+'\n'+dmap('wakeupCampusDomains',CAMPUS_DOMAINS,literal)
    code+="""

final _hostParsers = <String, List<String>>{
  for (final site in schoolPortalCatalog)
    Uri.parse(site.entry).host: wakeupSchoolBindings[site.name]!,
}..removeWhere((host, _) => _ambiguousHosts.contains(host));

final _ambiguousHosts = (() {
  final byHost = <String, Set<String>>{};
  for (final site in schoolPortalCatalog) {
    (byHost[Uri.parse(site.entry).host] ??= {}).add(site.name);
  }
  return byHost.keys.where((h) => byHost[h]!.length > 1).toSet();
})();

List<String> wakeupParsersFor(String schoolName, String host) =>
    wakeupSchoolBindings[schoolName] ??
    _hostParsers[host.toLowerCase()] ??
    const [];
"""
    (DEST/'wakeup_catalog.dart').write_text(code,encoding='utf8')
    (ROOT/'docs/product/priority-school-coverage.md').write_text(render_ledger(sites,bindings),encoding='utf8')
    print(f'{len(bindings)} named bindings; {len(sites)} curated HTTPS entries')
def main():
    p=argparse.ArgumentParser(); p.add_argument('--inputs',type=__import__('pathlib').Path); a=p.parse_args()
    def load(file,url):
        if a.inputs:return (a.inputs/file).read_text(encoding='utf-8-sig')
        with urlopen(url,timeout=30) as r:return r.read().decode('utf-8-sig')
    emit(*generate(json.loads(load('timetable.json',UPSTREAM)),json.loads(load('sleepy.json',CROSSCHECK)),load('legacy.kt',LEGACY)))

if __name__=='__main__':main()
